// The player simulator's report (docs/v2/PLAN.md M2). Run with `npm run sim`.
// It plays thousands of seeded matches with simulated people and writes
// docs/v2/sim/REPORT.md. Everything is seeded: the same code gives the same report.
import { mkdirSync, writeFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { createDrill, practiceStations, tutorialStations } from '../../src/engine/drill';
import { HIT_WINDOW_MS, createMatch } from '../../src/engine/match';
import { CAST } from '../../src/engine/personalities';
import { createRng } from '../../src/engine/rng';
import type { CpuStyle, HitWindow, Level, MatchConfig, MatchLength } from '../../src/engine/types';
import {
  addRun, mean, newTally, percent, quantile, share, summariseIntent, summariseSwings, type Tally,
} from '../../src/sim/analyse';
import { NETWORKS, SKILLS, phoneBot, type NetworkName, type SkillName } from '../../src/sim/players';
import { runMatch, type Bot } from '../../src/sim/runner';
import { buildBank } from '../../src/sim/swings';
import { templatesFor } from '../../tests/fixtures/templates';

const N = Number(process.env.SIM_MATCHES ?? 60);
const bank = buildBank(templatesFor(['teach', 'tuning']), createRng(20261110), { perTemplate: 6 });
const SKILL_NAMES = Object.keys(SKILLS) as SkillName[];
const LEVELS: Level[] = ['rookie', 'club', 'pro'];

const human = (skill: SkillName, seed: number, network: NetworkName = 'lan', window: HitWindow = 'normal'): Bot =>
  phoneBot(SKILLS[skill], bank, createRng(seed), NETWORKS[network], HIT_WINDOW_MS[window]);

interface Setup { window?: HitWindow; length?: MatchLength; network?: NetworkName }

function coop(skill: SkillName, style: CpuStyle, level: Level, setup: Setup = {}): Tally {
  const tally = newTally();
  for (let i = 0; i < N; i++) {
    const config: MatchConfig = {
      mode: 'singles', seats: [{ side: 'near', human: true, name: 'P' }, { side: 'far', human: false, style, level }],
      level, window: setup.window ?? 'normal', length: setup.length ?? 'games3', seed: 1000 + i,
    };
    const run = runMatch(createMatch(config, { firstServer: i % 2 ? 'near' : 'far' }), { 0: human(skill, 50_000 + i, setup.network, setup.window) });
    addRun(tally, run, [0]);
  }
  return tally;
}

function versus(a: SkillName, b: SkillName, setup: Setup = {}): Tally {
  const tally = newTally();
  for (let i = 0; i < N; i++) {
    const config: MatchConfig = {
      mode: 'singles', seats: [{ side: 'near', human: true, name: 'A' }, { side: 'far', human: true, name: 'B' }],
      level: 'club', window: setup.window ?? 'normal', length: setup.length ?? 'games3', seed: 3000 + i,
    };
    const run = runMatch(createMatch(config, { firstServer: i % 2 ? 'near' : 'far' }), { 0: human(a, 60_000 + i), 1: human(b, 70_000 + i) });
    addRun(tally, run);
  }
  return tally;
}

const row = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`;
const table = (head: string[], rows: (string | number)[][]) =>
  [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n');
const one = (x: number) => x.toFixed(1);
const errorsBy = (t: Tally, side: 'near' | 'far') => t.ends[side].out + t.ends[side].net + t.ends[side].missed + t.ends[side]['double-fault'];
const winnersBy = (t: Tally, side: 'near' | 'far') => t.ends[side].winner + t.ends[side].ace;

it('writes the simulator report', () => {
  const out: string[] = [];
  out.push('# Player simulator | report', '');
  out.push(`Generated by \`npm run sim\` (${N} matches per cell, all seeded). Simulated people swing synthetic phone swings`
    + ' built from the teach and tuning recordings and read by the real detector; their timing skill is an assumption'
    + ' (src/sim/players.ts), not a measurement. Match length is first to 3 games unless a table says otherwise.', '');

  // ---- 1. the swing bank ----
  const found = bank.filter((b) => b.detected);
  out.push('## 1. The synthetic swings', '');
  out.push(`${bank.length} synthetic swings from ${new Set(bank.map((b) => b.template)).size} recorded ones: `
    + `${percent(share(found.length, bank.length))} detected, ${percent(share(found.filter((b) => b.dirOk).length, found.length))} with the right direction, `
    + `median peak ${Math.round(quantile(found.map((b) => b.omega), 0.5))} deg/s, median power ${quantile(found.map((b) => b.power), 0.5).toFixed(2)}. `
    + 'The comparison with the held-out recordings is in tests/sim/swings.test.ts.', '');

  // ---- 2. the co-op ladder ----
  out.push('## 2. Against the computer: who wins', '');
  out.push('Share of matches the human wins, by skill (rows) and opponent (columns), Normal timing, home Wi-Fi.', '');
  const ladderRows: (string | number)[][] = [];
  const rallyRows: (string | number)[][] = [];
  const cells = new Map<string, Tally>();
  for (const skill of SKILL_NAMES) {
    const wins: (string | number)[] = [SKILLS[skill].name];
    const rallies: (string | number)[] = [SKILLS[skill].name];
    for (const level of LEVELS) {
      for (const c of CAST) {
        const t = coop(skill, c.style, level);
        cells.set(`${skill}:${c.style}:${level}`, t);
        expect(t.timedOut, `${skill} against ${c.style} ${level} finished`).toBe(0);
        wins.push(percent(share(t.nearWins, t.matches)));
        rallies.push(one(share(t.shots, t.points)));
      }
    }
    ladderRows.push(wins);
    rallyRows.push(rallies);
  }
  const head = ['Human', ...LEVELS.flatMap((l) => CAST.map((c) => `${c.name.replace('The ', '')} ${l}`))];
  out.push(table(head, ladderRows), '');
  out.push('Shots per point in the same matches.', '', table(head, rallyRows), '');

  // ---- 3. how points end ----
  out.push('## 3. How points end', '');
  out.push('Against The Regular at each level. "Human errs" is the human hitting out, into the net, missing, or double faulting;'
    + ' "CPU errs" the same for the computer; winners include aces.', '');
  const endRows: (string | number)[][] = [];
  for (const skill of SKILL_NAMES) {
    for (const level of LEVELS) {
      const t = cells.get(`${skill}:allround:${level}`)!;
      endRows.push([
        SKILLS[skill].name, level, percent(share(errorsBy(t, 'near'), t.points)), percent(share(winnersBy(t, 'near'), t.points)),
        percent(share(errorsBy(t, 'far'), t.points)), percent(share(winnersBy(t, 'far'), t.points)),
        one(quantile(t.rallies, 0.5)), one(quantile(t.rallies, 0.9)), one(mean(t.minutes)),
      ]);
    }
  }
  out.push(table(['Human', 'CPU level', 'Human errs', 'Human winners', 'CPU errs', 'CPU winners', 'Median rally', '90th pct rally', 'Minutes'], endRows), '');

  // ---- 4. timing windows and the racket face ----
  out.push('## 4. Timing windows: where the ball meets the strings', '');
  out.push('Rally swings against The Regular (club). "Not counted" swings were too early, too late, or the message came after the ball was gone.', '');
  const faceRows: (string | number)[][] = [];
  for (const skill of SKILL_NAMES) {
    for (const window of ['easy', 'normal', 'pro'] as const) {
      const t = window === 'normal' ? cells.get(`${skill}:allround:club`)! : coop(skill, 'allround', 'club', { window });
      const s = summariseSwings(t.swings);
      const f = (k: string) => percent(s.face[k] ?? 0);
      faceRows.push([
        SKILLS[skill].name, window, percent(s.hit), percent(s.whiff), percent(s.ignored),
        f('sweet'), f('centre'), f('tip'), f('throat'), f('edge'), f('frame'), percent(s.landedIn), percent(share(t.nearWins, t.matches)),
      ]);
    }
  }
  out.push(table(['Human', 'Window', 'Hit', 'Whiff', 'Not counted', 'Sweet', 'Centre', 'Tip', 'Throat', 'Edge', 'Frame', 'Hits landing in', 'Matches won'], faceRows), '');

  // ---- 5. intent ----
  out.push('## 5. Does a well-timed swing do what the player meant?', '');
  out.push('Aimed swings only (meant cross-court or down the line). "Well timed" is within 30 ms of the timing the player was aiming for.'
    + ' "As meant" is struck, in, and on the side the player wanted.', '');
  const intentRows: (string | number)[][] = [];
  for (const skill of SKILL_NAMES) {
    if (SKILLS[skill].aim === 0) continue;
    for (const window of ['easy', 'normal', 'pro'] as const) {
      const t = window === 'normal' ? cells.get(`${skill}:allround:club`)! : coop(skill, 'allround', 'club', { window });
      const s = summariseIntent(t.swings, SKILLS[skill].aimU * HIT_WINDOW_MS[window]);
      intentRows.push([
        SKILLS[skill].name, window, s.aimed, percent(share(s.wellTimed, s.aimed)), percent(s.struck), percent(s.asMeant),
        percent(s.asMeantAll), percent(s.safeIn),
      ]);
    }
  }
  out.push(table(['Human', 'Window', 'Aimed swings', 'Well timed', 'Well timed: struck', 'Well timed: as meant', 'All aimed: as meant', 'Unaimed hits landing in'], intentRows), '');

  // ---- 6. versus ----
  out.push('## 6. Versus: person against person', '');
  const versusRows: (string | number)[][] = [];
  const pairs: [SkillName, SkillName][] = [
    ['beginner', 'beginner'], ['casual', 'casual'], ['regular', 'regular'], ['good', 'good'], ['sharp', 'sharp'],
    ['casual', 'beginner'], ['regular', 'casual'], ['good', 'regular'], ['sharp', 'good'], ['good', 'beginner'],
  ];
  for (const [a, b] of pairs) {
    const t = versus(a, b);
    expect(t.timedOut, `${a} against ${b} finished`).toBe(0);
    versusRows.push([
      `${SKILLS[a].name} v ${SKILLS[b].name}`, percent(share(t.nearWins, t.matches)), one(share(t.shots, t.points)),
      one(quantile(t.rallies, 0.5)), one(quantile(t.rallies, 0.9)), percent(share(winnersBy(t, 'near') + winnersBy(t, 'far'), t.points)),
      one(mean(t.minutes)), one(quantile(t.minutes, 0.9)),
    ]);
  }
  out.push(table(['Pairing (near v far)', 'Near wins', 'Shots per point', 'Median rally', '90th pct rally', 'Points won by a winner', 'Minutes', '90th pct minutes'], versusRows), '');

  // ---- 7. the network ----
  out.push('## 7. The network', '');
  out.push('A Regular player against The Regular (club) on each network.', '');
  const netRows: (string | number)[][] = [];
  for (const network of Object.keys(NETWORKS) as NetworkName[]) {
    const t = network === 'lan' ? cells.get('regular:allround:club')! : coop('regular', 'allround', 'club', { network });
    const s = summariseSwings(t.swings);
    netRows.push([
      NETWORKS[network].name, Math.round(mean(t.swings.map((x) => x.lag))), Math.round(quantile(t.swings.map((x) => x.lag), 0.99)),
      percent(s.hit), percent(s.ignored), percent(s.landedIn), percent(share(t.nearWins, t.matches)),
    ]);
  }
  out.push(table(['Network', 'Mean lag, ms', '99th pct lag, ms', 'Hit', 'Not counted', 'Hits landing in', 'Matches won'], netRows), '');

  // ---- 8. drills ----
  out.push('## 8. Tutorial and practice', '');
  const drillRows: (string | number)[][] = [];
  for (const skill of SKILL_NAMES) {
    const minutes: number[] = [];
    let finished = 0;
    const scores: number[] = [];
    for (let i = 0; i < Math.max(20, Math.round(N / 2)); i++) {
      // The tutorial is followed as it asks: early on "Swing early", late on "Swing late", topspin when asked.
      const base = human(skill, 80_000 + i, 'lan', 'easy');
      const rng = createRng(81_000 + i);
      const follow: Bot = {
        ...base,
        swing(ctx) {
          const s = base.swing(ctx);
          const title = ctx.view.drill?.title;
          if (!s || ctx.kind === 'serve') return s;
          const meant = title === 'Swing early' ? -90 : title === 'Swing late' ? 90 : 0;
          return { ...s, dt: s.dt + meant, spin: title === 'Topspin' ? Math.max(s.spin, 0.3 + rng() * 0.4) : s.spin };
        },
      };
      const run = runMatch(createDrill({ kind: 'tutorial', stations: tutorialStations(), window: 'easy', seed: 4000 + i }), { 0: follow }, { maxMs: 15 * 60_000 });
      if (!run.timedOut) { finished++; minutes.push(run.ms / 60_000); }
      const practice = runMatch(createDrill({ kind: 'practice', stations: practiceStations('club'), window: 'normal', seed: 5000 + i }), { 0: human(skill, 82_000 + i) });
      scores.push(practice.view.drill?.score ?? 0);
    }
    drillRows.push([
      SKILLS[skill].name, percent(share(finished, Math.max(20, Math.round(N / 2)))), one(quantile(minutes, 0.5)), one(quantile(minutes, 0.9)),
      one(mean(scores)),
    ]);
  }
  out.push('The tutorial on Easy timing, followed as it asks; and a 15-ball target practice basket (club), 3 points for the lit zone, 1 for any ball in.', '');
  out.push(table(['Human', 'Tutorial finished within 15 min', 'Median minutes', '90th pct minutes', 'Practice score (of 45)'], drillRows), '');

  mkdirSync('docs/v2/sim', { recursive: true });
  writeFileSync('docs/v2/sim/REPORT.md', out.join('\n') + '\n');
  console.log(`wrote docs/v2/sim/REPORT.md (${out.length} lines)`);
});
